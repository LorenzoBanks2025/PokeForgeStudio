/**
 * @file pretExporter.ts
 * @package pokecompiler
 * @description Generates pret/pokeemerald and pret/pokefirered compatible C decomp trees.
 */

import JSZip from 'jszip';
import type { DecompiledProject } from '../pokedcomp/types.ts';

export class PretExporter {
  static async exportSourceZip(project: DecompiledProject, logs: string[]): Promise<Blob> {
    logs.push(`Generating pret-compatible C decompilation source tree for [${project.projectName}]...`);
    const zip = new JSZip();

    // 1. Root Makefile
    const makefile = `# Makefile for ${project.projectName}
# Built with PokéForge Studio
# Requires: devkitARM and gcc-arm-none-eabi

SHELL := /bin/bash
ROM := ${project.projectName}.gba
TITLE := ${project.game === 'emerald' ? 'POKEMON EMER' : 'POKEMON FIRE'}
GAME_CODE := ${project.game === 'emerald' ? 'BPEE' : 'BPRE'}

CC := arm-none-eabi-gcc
AS := arm-none-eabi-as
LD := arm-none-eabi-ld
OBJCOPY := arm-none-eabi-objcopy

CFLAGS := -mthumb -mthumb-interwork -O2 -Wall -fno-strict-aliasing

all: $(ROM)

$(ROM): main.elf
\t$(OBJCOPY) -O binary main.elf $(ROM)
\tgbagfx -fix $(ROM)

clean:
\trm -f *.o main.elf $(ROM)

.PHONY: all clean
`;
    zip.file('Makefile', makefile);

    // 2. README.md
    const readme = `# ${project.projectName} (${project.game.toUpperCase()})

This source tree was generated by **PokéForge Studio**.
It is 100% compatible with the \`pret/${project.game === 'emerald' ? 'pokeemerald' : 'pokefirered'}\` decompilation structure.

## Quick Start
1. Install \`devkitARM\` and \`gcc-arm-none-eabi\`.
2. Run \`make\` to build \`${project.projectName}.gba\`.
3. To test immediately in your browser or desktop, use PokéForge Studio's WebAssembly recompiler.
`;
    zip.file('README.md', readme);

    // 3. include/constants/species.h
    let speciesHeader = `// Generated by PokéForge Studio\n#ifndef GUARD_CONSTANTS_SPECIES_H\n#define GUARD_CONSTANTS_SPECIES_H\n\n`;
    Object.values(project.species).forEach((sp, idx) => {
      speciesHeader += `#define ${sp.id} ${idx + 1}\n`;
    });
    speciesHeader += `\n#endif // GUARD_CONSTANTS_SPECIES_H\n`;
    zip.file('include/constants/species.h', speciesHeader);

    // 4. include/constants/items.h
    let itemsHeader = `// Generated by PokéForge Studio\n#ifndef GUARD_CONSTANTS_ITEMS_H\n#define GUARD_CONSTANTS_ITEMS_H\n\n`;
    Object.values(project.items).forEach((item, idx) => {
      itemsHeader += `#define ${item.id} ${idx + 1}\n`;
    });
    itemsHeader += `\n#endif // GUARD_CONSTANTS_ITEMS_H\n`;
    zip.file('include/constants/items.h', itemsHeader);

    // 5. include/constants/moves.h
    let movesHeader = `// Generated by PokéForge Studio\n#ifndef GUARD_CONSTANTS_MOVES_H\n#define GUARD_CONSTANTS_MOVES_H\n\n`;
    Object.values(project.moves).forEach((move, idx) => {
      movesHeader += `#define ${move.id} ${idx + 1}\n`;
    });
    movesHeader += `\n#endif // GUARD_CONSTANTS_MOVES_H\n`;
    zip.file('include/constants/moves.h', movesHeader);

    // 6. src/data/pokemon/base_stats.h
    let baseStatsCode = `// Generated by PokéForge Studio\nconst struct SpeciesInfo gSpeciesInfo[] = {\n`;
    Object.values(project.species).forEach(sp => {
      baseStatsCode += `    [${sp.id}] = {\n`;
      baseStatsCode += `        .baseHP = ${sp.baseStats.hp},\n`;
      baseStatsCode += `        .baseAttack = ${sp.baseStats.attack},\n`;
      baseStatsCode += `        .baseDefense = ${sp.baseStats.defense},\n`;
      baseStatsCode += `        .baseSpeed = ${sp.baseStats.speed},\n`;
      baseStatsCode += `        .baseSpAttack = ${sp.baseStats.spAttack},\n`;
      baseStatsCode += `        .baseSpDefense = ${sp.baseStats.spDefense},\n`;
      baseStatsCode += `        .types = { TYPE_${sp.types[0]}, TYPE_${sp.types[1] ?? sp.types[0]} },\n`;
      baseStatsCode += `        .catchRate = ${sp.catchRate},\n`;
      baseStatsCode += `        .expYield = ${sp.baseExpYield},\n`;
      baseStatsCode += `        .abilities = { ABILITY_${sp.abilities[0].toUpperCase().replace(/\s+/g, '_')}, ${sp.abilities[1] ? 'ABILITY_' + sp.abilities[1].toUpperCase().replace(/\s+/g, '_') : 'ABILITY_NONE'} },\n`;
      baseStatsCode += `    },\n`;
    });
    baseStatsCode += `};\n`;
    zip.file('src/data/pokemon/base_stats.h', baseStatsCode);

    // 7. Wild Encounters JSON
    zip.file('src/data/wild_encounters.json', JSON.stringify(project.wildEncounters, null, 2));

    // 8. Maps & Event Scripts
    for (const [mapId, mapData] of Object.entries(project.maps)) {
      const mapDir = `data/maps/${mapId}`;
      zip.file(`${mapDir}/map.json`, JSON.stringify({
        id: mapData.layout.id,
        name: mapData.layout.name,
        width: mapData.layout.width,
        height: mapData.layout.height,
        tileset: mapData.layout.tilesetId,
        music: mapData.layout.music,
        events: mapData.events
      }, null, 2));

      // Event scripts file (.inc)
      let scriptsInc = `@ Map scripts for ${mapId}\n`;
      for (const npc of mapData.events.npcs) {
        if (project.scripts[npc.scriptId]) {
          scriptsInc += `\n${project.scripts[npc.scriptId].code}\n`;
        }
      }
      for (const sign of mapData.events.signs) {
        if (project.scripts[sign.scriptId]) {
          scriptsInc += `\n${project.scripts[sign.scriptId].code}\n`;
        }
      }
      zip.file(`${mapDir}/scripts.inc`, scriptsInc);
    }

    logs.push(`✓ Assembled pret C decompilation tree with ${Object.keys(zip.files).length} files.`);
    const blob = await zip.generateAsync({ type: 'blob' });
    logs.push(`✓ Pret C source ZIP generated (${Math.round(blob.size / 1024)} KB).`);
    return blob;
  }
}
